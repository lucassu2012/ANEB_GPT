def main(
    argv: Sequence[str] | None = None,
    *,
    stdout: TextIO | None = None,
    stderr: TextIO | None = None,
) -> int:
    stdout = stdout or sys.stdout
    stderr = stderr or sys.stderr
    args = build_parser().parse_args(argv)
    try:
        outcome = verify_and_transition(_config_from_args(args))
    except VerificationError as error:
        print(f"ERROR code={error.code}", file=stderr)
        return 2
    if outcome.success:
        print("OK verification=passed transition=handoff->idle", file=stdout)
        return 0
    print(
        f"ERROR code={outcome.code} transition={outcome.transition}",
        file=stderr,
    )
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
