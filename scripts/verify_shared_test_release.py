def _probe_server(
    config: VerificationConfig, run_command: RunCommand
) -> Mapping[str, object]:
    command = [
        config.ssh_path,
        "-T",
        "-p",
        str(config.ssh_port),
        "-i",
        str(config.ssh_key),
        "-o",
        "BatchMode=yes",
        "-o",
        "StrictHostKeyChecking=yes",
        "-o",
        "UpdateHostKeys=no",
        "-o",
        "ConnectTimeout=10",
        config.ssh_host,
        "python3",
        "-",
    ]
    completed = _run(
        run_command,
        command,
        input_text=SERVER_PROBE_SCRIPT,
        timeout=config.command_timeout_seconds,
        failure_code="e01_probe_failed",
    )
    if completed.stderr.strip():
        raise VerificationError("e01_probe_stderr")
    try:
        payload = json.loads(completed.stdout)
    except json.JSONDecodeError as error:
        raise VerificationError("e01_probe_json_invalid") from error
    if not isinstance(payload, dict) or set(payload) != SERVER_KEYS:
        raise VerificationError("e01_probe_schema_invalid")
    if payload["schema"] != "aneb-shared-release-server-probe-v1":
        raise VerificationError("e01_probe_schema_invalid")
    if payload["serverinfo_version"] != config.expected_version:
        raise VerificationError("e01_version_mismatch")
    if payload["h3_enabled"] is not True:
        raise VerificationError("e01_h3_disabled")
    if payload["service_active"] is not True:
        raise VerificationError("e01_service_inactive")

    expected = {
        "binary_sha256": config.expected_binary_sha256,
        "qdisc_sha256": config.expected_qdisc_sha256,
        "firewall_full_sha256": config.expected_firewall_full_sha256,
        "firewall_v4_sha256": config.expected_firewall_v4_sha256,
        "firewall_v6_sha256": config.expected_firewall_v6_sha256,
        "firewall_nft_sha256": config.expected_firewall_nft_sha256,
    }
    for key, expected_value in expected.items():
        actual = payload[key]
        if not isinstance(actual, str) or SHA256_RE.fullmatch(actual) is None:
            raise VerificationError("e01_sha256_invalid")
        if actual != expected_value:
            raise VerificationError(f"e01_{key}_mismatch")
    for key in (
        "wg_aneb_lab_present",
        "ifb_aneb_lab_present",
        "aneb_lab_present",
        "udp_51820_present",
    ):
        if payload[key] is not False:
            raise VerificationError("e01_phase0_residue_present")
    return payload


def _read_handoff(path: Path) -> tuple[bytes, str]:
    try:
        payload = path.read_bytes()
        document = StatusDocument.parse(payload)
    except (OSError, StatusError) as error:
        raise VerificationError("status_file_unreadable") from error
    if document.snapshot.state != HANDOFF:
        raise VerificationError("status_not_handoff")
    return payload, _sha256(payload)


def _assert_status_unchanged(path: Path, baseline: bytes, digest: str) -> None:
    try:
        current = path.read_bytes()
    except OSError as error:
        raise VerificationError("status_changed_during_review") from error
    if current != baseline or _sha256(current) != digest:
        raise VerificationError("status_changed_during_review")


def _transition_status(
    config: VerificationConfig,
    run_command: RunCommand,
    *,
    command: str,
    baseline: bytes,
    baseline_sha256: str,
    evidence: str,
) -> None:
    _assert_status_unchanged(config.status_file, baseline, baseline_sha256)
    completed = _run(
        run_command,
        [
            sys.executable,
            str(config.status_updater),
            "--status-file",
            str(config.status_file),
            command,
            "--executor",
            REVIEWER,
            "--expected-status-sha256",
            baseline_sha256,
            "--evidence",
            evidence,
        ],
        timeout=config.command_timeout_seconds,
        failure_code=f"status_{command.replace('-', '_')}_failed",
    )
    if completed.stderr.strip():
        raise VerificationError(f"status_{command.replace('-', '_')}_failed")
    try:
        state = StatusDocument.parse(config.status_file.read_bytes()).snapshot.state
    except (OSError, StatusError) as error:
        raise VerificationError("status_transition_result_invalid") from error
    expected_state = IDLE if command == "review-release" else LOCKED
    if state != expected_state:
        raise VerificationError("status_transition_result_invalid")


def _interval_label(config: VerificationConfig) -> str:
    interval_value = float(config.interval_seconds)
    return (
        str(int(interval_value))
        if interval_value.is_integer()
        else format(interval_value, "g")
    )


def _success_evidence(config: VerificationConfig) -> str:
    interval = _interval_label(config)
    return (
        f"T+0/T+{interval} 自动独立复核通过：精确设备，5包 PID/ServiceRecord=0，"
        "ANEB 无障碍未启用/未绑定，tun0/VPN=0，Launcher 前台，stayon=0，"
        "Wi-Fi CONNECTED+VALIDATED；"
        f"E-01 {config.expected_version}/active，binary/qdisc/firewall "
        "full/v4/v6/nft 双轮精确且稳定，Phase0 残留=0。"
    )


def _failure_evidence(code: str, config: VerificationConfig) -> str:
    safe_code = re.sub(r"[^a-z0-9_]+", "_", code.casefold())[:96]
    interval = _interval_label(config)
    return (
        f"自动独立复核失败并锁定：T+0/T+{interval} 只读探针未全部通过；"
        f"code={safe_code}。"
    )


def verify_and_transition(
    config: VerificationConfig,
    *,
    run_command: RunCommand = subprocess.run,
    sleep: Sleep = time.sleep,
) -> VerificationOutcome:
    config = _validate_config(config)
    baseline, baseline_sha256 = _read_handoff(config.status_file)
    first_server: Mapping[str, object] | None = None
    try:
        _probe_p40(config, run_command)
        first_server = _probe_server(config, run_command)
        _assert_status_unchanged(config.status_file, baseline, baseline_sha256)
        sleep(config.interval_seconds)
        _assert_status_unchanged(config.status_file, baseline, baseline_sha256)
        _probe_p40(config, run_command)
        second_server = _probe_server(config, run_command)
        _assert_status_unchanged(config.status_file, baseline, baseline_sha256)
        if any(first_server[key] != second_server[key] for key in SERVER_HASH_KEYS):
            raise VerificationError("e01_fingerprints_unstable")
    except VerificationError as error:
        if error.code == "status_changed_during_review":
            return VerificationOutcome(False, error.code, "none", baseline_sha256)
        try:
            _transition_status(
                config,
                run_command,
                command="review-lock",
                baseline=baseline,
                baseline_sha256=baseline_sha256,
                evidence=_failure_evidence(error.code, config),
            )
        except VerificationError as transition_error:
            return VerificationOutcome(
                False,
                transition_error.code,
                "none",
                baseline_sha256,
            )
        return VerificationOutcome(False, error.code, "locked", baseline_sha256)

    try:
        _transition_status(
            config,
            run_command,
            command="review-release",
            baseline=baseline,
            baseline_sha256=baseline_sha256,
            evidence=_success_evidence(config),
        )
    except VerificationError as release_error:
        # A concurrent writer owns the new state; never try to overwrite it.
        try:
            _assert_status_unchanged(config.status_file, baseline, baseline_sha256)
        except VerificationError:
            return VerificationOutcome(
                False,
                "status_changed_during_review",
                "none",
                baseline_sha256,
            )
        # The probes passed but the atomic release itself failed.  Lock the
        # still-original handoff rather than leaving an ambiguous success.
        try:
            _transition_status(
                config,
                run_command,
                command="review-lock",
                baseline=baseline,
                baseline_sha256=baseline_sha256,
                evidence=_failure_evidence(release_error.code, config),
            )
        except VerificationError as lock_error:
            return VerificationOutcome(
                False,
                lock_error.code,
                "none",
                baseline_sha256,
            )
        return VerificationOutcome(
            False,
            release_error.code,
            "locked",
            baseline_sha256,
        )
    return VerificationOutcome(True, "verified", "released", baseline_sha256)


