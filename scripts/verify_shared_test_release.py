class VerificationError(Exception):
    """A bounded, non-sensitive verification failure."""

    def __init__(self, code: str) -> None:
        super().__init__(code)
        self.code = code


RunCommand = Callable[..., subprocess.CompletedProcess[str]]
Sleep = Callable[[float], None]


@dataclass(frozen=True)
class VerificationConfig:
    status_file: Path
    status_updater: Path
    adb_path: str
    adb_serial: str
    ssh_path: str
    ssh_host: str
    ssh_key: Path
    ssh_port: int
    expected_version: str
    expected_binary_sha256: str
    expected_qdisc_sha256: str
    expected_firewall_full_sha256: str
    expected_firewall_v4_sha256: str
    expected_firewall_v6_sha256: str
    expected_firewall_nft_sha256: str
    interval_seconds: float = 10.0
    command_timeout_seconds: float = 30.0


@dataclass(frozen=True)
class VerificationOutcome:
    success: bool
    code: str
    transition: str
    original_status_sha256: str


def _sha256(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def _validate_config(config: VerificationConfig) -> VerificationConfig:
    if SERIAL_RE.fullmatch(config.adb_serial) is None:
        raise VerificationError("adb_serial_invalid")
    if (
        SSH_HOST_RE.fullmatch(config.ssh_host) is None
        or config.ssh_host.startswith("-")
    ):
        raise VerificationError("ssh_host_invalid")
    if VERSION_RE.fullmatch(config.expected_version) is None:
        raise VerificationError("expected_version_invalid")
    if not 1 <= config.ssh_port <= 65535:
        raise VerificationError("ssh_port_invalid")
    try:
        interval_seconds = float(config.interval_seconds)
    except (TypeError, ValueError) as error:
        raise VerificationError("interval_invalid") from error
    if not 10 <= interval_seconds <= 300:
        raise VerificationError("interval_invalid")
    if not 1 <= config.command_timeout_seconds <= 300:
        raise VerificationError("command_timeout_invalid")
    for value in (
        config.expected_binary_sha256,
        config.expected_qdisc_sha256,
        config.expected_firewall_full_sha256,
        config.expected_firewall_v4_sha256,
        config.expected_firewall_v6_sha256,
        config.expected_firewall_nft_sha256,
    ):
        if SHA256_RE.fullmatch(value.lower()) is None:
            raise VerificationError("expected_sha256_invalid")
    if config.status_file.is_symlink() or not config.status_file.is_file():
        raise VerificationError("status_file_invalid")
    if config.status_updater.is_symlink() or not config.status_updater.is_file():
        raise VerificationError("status_updater_invalid")
    if config.ssh_key.is_symlink() or not config.ssh_key.is_file():
        raise VerificationError("ssh_key_invalid")
    return replace(
        config,
        expected_binary_sha256=config.expected_binary_sha256.lower(),
        expected_qdisc_sha256=config.expected_qdisc_sha256.lower(),
        expected_firewall_full_sha256=config.expected_firewall_full_sha256.lower(),
        expected_firewall_v4_sha256=config.expected_firewall_v4_sha256.lower(),
        expected_firewall_v6_sha256=config.expected_firewall_v6_sha256.lower(),
        expected_firewall_nft_sha256=config.expected_firewall_nft_sha256.lower(),
        interval_seconds=interval_seconds,
    )


def _run(
    run_command: RunCommand,
    arguments: Sequence[str],
    *,
    timeout: float,
    input_text: str | None = None,
    allowed_returncodes: tuple[int, ...] = (0,),
    failure_code: str = "external_command_failed",
) -> subprocess.CompletedProcess[str]:
    try:
        completed = run_command(
            list(arguments),
            input=input_text,
            text=True,
            capture_output=True,
            timeout=timeout,
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as error:
        raise VerificationError(failure_code) from error
    if completed.returncode not in allowed_returncodes:
        raise VerificationError(failure_code)
    if not isinstance(completed.stdout, str) or not isinstance(completed.stderr, str):
        raise VerificationError(failure_code)
    return completed


def _adb(
    config: VerificationConfig,
    run_command: RunCommand,
    *arguments: str,
    allowed_returncodes: tuple[int, ...] = (0,),
) -> subprocess.CompletedProcess[str]:
    return _run(
        run_command,
        [config.adb_path, "-s", config.adb_serial, *arguments],
        timeout=config.command_timeout_seconds,
        allowed_returncodes=allowed_returncodes,
        failure_code="adb_probe_failed",
    )


def _network_agent_blocks(payload: str) -> tuple[str, ...]:
    markers = list(re.finditer(r"\bNetwork(?:AgentInfo|Request)\b", payload))
    blocks: list[str] = []
    for index, marker in enumerate(markers):
        if marker.group(0) != "NetworkAgentInfo":
            continue
        end = markers[index + 1].start() if index + 1 < len(markers) else len(payload)
        blocks.append(payload[marker.start():end])
    return tuple(blocks)


def _has_transport(block: str, transport: str) -> bool:
    return re.search(
        rf"\bTransports\s*:\s*[^\]\r\n}}]*\b{re.escape(transport)}\b",
        block,
        flags=re.IGNORECASE,
    ) is not None


def _probe_p40(config: VerificationConfig, run_command: RunCommand) -> None:
    serial = _adb(config, run_command, "get-serialno").stdout.strip()
    if serial != config.adb_serial:
        raise VerificationError("adb_serial_mismatch")

    for package in PACKAGES:
        pid = _adb(
            config,
            run_command,
            "shell",
            "pidof",
            package,
            allowed_returncodes=(0, 1),
        )
        if pid.returncode != 1 or pid.stdout.strip():
            raise VerificationError("p40_package_pid_active")
        services = _adb(
            config,
            run_command,
            "shell",
            "dumpsys",
            "activity",
            "services",
            package,
        ).stdout
        if SERVICE_RECORD_RE.search(services):
            raise VerificationError("p40_service_record_active")

    enabled_accessibility = _adb(
        config,
        run_command,
        "shell",
        "settings",
        "get",
        "secure",
        "enabled_accessibility_services",
    ).stdout.strip()
    enabled_components = {
        component.strip()
        for component in enabled_accessibility.split(":")
        if component.strip() and component.strip().casefold() != "null"
    }
    if any(
        component == package or component.startswith(package + "/")
        for component in enabled_components
        for package in ANEB_PACKAGES
    ):
        raise VerificationError("p40_aneb_accessibility_enabled")

    accessibility_dump = _adb(
        config, run_command, "shell", "dumpsys", "accessibility"
    ).stdout
    for line in accessibility_dump.splitlines():
        # A configured shortcut target is inert and is deliberately preserved.
        if SHORTCUT_TARGET_ONLY_RE.fullmatch(line.strip()):
            continue
        if any(package in line for package in ANEB_PACKAGES):
            raise VerificationError("p40_aneb_accessibility_bound")

    links = _adb(config, run_command, "shell", "ip", "-o", "link", "show").stdout
    if TUN0_RE.search(links):
        raise VerificationError("p40_tun0_active")

    connectivity = _adb(
        config, run_command, "shell", "dumpsys", "connectivity"
    ).stdout
    agents = _network_agent_blocks(connectivity)
    if any(_has_transport(block, "VPN") for block in agents):
        raise VerificationError("p40_vpn_network_agent_active")
    wifi_agents = [block for block in agents if _has_transport(block, "WIFI")]
    if not any(
        re.search(r"\bCONNECTED\b", block, flags=re.IGNORECASE)
        and re.search(r"\bVALIDATED\b", block, flags=re.IGNORECASE)
        for block in wifi_agents
    ):
        raise VerificationError("p40_validated_wifi_missing")

    activities = _adb(
        config, run_command, "shell", "dumpsys", "activity", "activities"
    ).stdout
    resumed = [line for line in activities.splitlines() if RESUMED_RE.search(line)]
    if not resumed or not any(LAUNCHER_COMPONENT in line for line in resumed):
        raise VerificationError("p40_launcher_not_foreground")

    stayon = _adb(
        config,
        run_command,
        "shell",
        "settings",
        "get",
        "global",
        "stay_on_while_plugged_in",
    ).stdout.strip().casefold()
    if stayon not in {"0", "false"}:
        raise VerificationError("p40_stayon_enabled")


