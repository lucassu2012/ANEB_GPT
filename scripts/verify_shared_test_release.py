def canonicalize_iptables_save(data, expected_tool):
    if not data:
        raise SystemExit("empty iptables-save snapshot")
    lines = data.splitlines(keepends=True)
    if len(lines) < 2:
        raise SystemExit("incomplete iptables-save snapshot")
    bodies = [line.rstrip(b"\r\n") for line in lines]
    generated = [
        index for index, body in enumerate(bodies)
        if body.startswith(b"# Generated by")
    ]
    completed = [
        index for index, body in enumerate(bodies)
        if body.startswith(b"# Completed on")
    ]
    if generated != [0] or completed != [len(lines) - 1]:
        raise SystemExit("iptables-save wrapper positions invalid")

    expected = expected_tool.encode("ascii")
    header = bodies[0]
    header_prefix = b"# Generated by " + expected + b" "
    if not header.startswith(header_prefix):
        raise SystemExit("iptables-save tool identity mismatch")
    identity, separator, generated_timestamp = header.rpartition(b" on ")
    if (
        not separator
        or not identity.startswith(header_prefix)
        or not identity[len(header_prefix):].strip()
    ):
        raise SystemExit("malformed iptables-save header")
    completed_prefix = b"# Completed on "
    if not bodies[-1].startswith(completed_prefix):
        raise SystemExit("malformed iptables-save footer")
    completed_timestamp = bodies[-1][len(completed_prefix):]

    timestamp_pattern = re.compile(
        rb"(?:Mon|Tue|Wed|Thu|Fri|Sat|Sun) "
        rb"(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) "
        rb"(?: [1-9]|[12][0-9]|3[01]) "
        rb"(?:[01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9] [0-9]{4}"
    )

    def validate_timestamp(value):
        if timestamp_pattern.fullmatch(value) is None:
            raise SystemExit("malformed iptables-save timestamp")
        try:
            text = value.decode("ascii")
            parsed = datetime.strptime(text, "%a %b %d %H:%M:%S %Y")
        except (UnicodeDecodeError, ValueError) as error:
            raise SystemExit("invalid iptables-save timestamp") from error
        canonical = "{} {:2d} {}".format(
            parsed.strftime("%a %b"),
            parsed.day,
            parsed.strftime("%H:%M:%S %Y"),
        )
        if text != canonical:
            raise SystemExit("non-canonical iptables-save timestamp")

    validate_timestamp(generated_timestamp)
    validate_timestamp(completed_timestamp)
    newline = (
        b"\r\n" if lines[0].endswith(b"\r\n")
        else b"\n" if lines[0].endswith(b"\n")
        else b""
    )
    if not newline:
        raise SystemExit("iptables-save header lacks newline")
    return identity + newline + b"".join(lines[1:-1])


