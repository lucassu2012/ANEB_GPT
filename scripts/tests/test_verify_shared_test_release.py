    def test_each_package_pid_and_service_record_is_checked(self) -> None:
        for package in PACKAGES:
            for failure_kind in ("pid", "service"):
                with self.subTest(package=package, failure=failure_kind):
                    set_status_state(self.status, HANDOFF)
                    runner = FakeRunner(self.status)
                    if failure_kind == "pid":
                        runner.pid_package = package
                        expected = "p40_package_pid_active"
                    else:
                        runner.service_package = package
                        expected = "p40_service_record_active"
                    outcome = verify_and_transition(
                        self.config,
                        run_command=runner,
                        sleep=lambda _: None,
                    )
                    self.assertEqual(expected, outcome.code)
                    self.assertEqual("locked", outcome.transition)

