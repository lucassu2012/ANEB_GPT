    def test_extracted_server_canonicalizer_ignores_only_valid_run_times(self) -> None:
        canonicalize = extracted_canonicalizer()
        first_raw = iptables_snapshot("Sat Jul 18 19:00:00 2026")
        second_raw = iptables_snapshot("Sat Jul 18 19:00:02 2026")
        first = canonicalize(first_raw, "iptables-save")
        second = canonicalize(second_raw, "iptables-save")
        self.assertEqual(first, second)
        self.assertEqual(hashlib.sha256(first).digest(), hashlib.sha256(second).digest())
        self.assertIn(b"iptables-save v1.8.7 (nf_tables)", first)
        self.assertNotIn(b"19:00:00", first)
        self.assertNotIn(b"# Completed on", first)

        semantic_changes = {
            "rule": iptables_snapshot("Sat Jul 18 19:00:02 2026", port=8444),
            "policy": iptables_snapshot(
                "Sat Jul 18 19:00:02 2026", policy="DROP"
            ),
            "tool-version": iptables_snapshot(
                "Sat Jul 18 19:00:02 2026", version="v1.8.8"
            ),
            "tool-backend": iptables_snapshot(
                "Sat Jul 18 19:00:02 2026", backend="legacy"
            ),
        }
        for name, changed_raw in semantic_changes.items():
            with self.subTest(name=name):
                changed = canonicalize(changed_raw, "iptables-save")
                self.assertNotEqual(first, changed)
                self.assertNotEqual(
                    hashlib.sha256(first).digest(),
                    hashlib.sha256(changed).digest(),
                )

        malformed = {
            "missing-header": b"*filter\nCOMMIT\n# Completed on Sat Jul 18 19:00:00 2026\n",
            "missing-footer": first_raw.rsplit(b"# Completed on", 1)[0],
            "duplicated-wrapper": first_raw + first_raw,
            "malformed-time": first_raw.replace(
                b"Sat Jul 18 19:00:00 2026", b"2026-07-18T19:00:00", 1
            ),
        }
        for name, payload in malformed.items():
            with self.subTest(name=name):
                with self.assertRaises(SystemExit):
                    canonicalize(payload, "iptables-save")
        with self.assertRaises(SystemExit):
            canonicalize(first_raw, "ip6tables-save")

